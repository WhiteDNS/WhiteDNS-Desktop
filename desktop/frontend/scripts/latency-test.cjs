const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(require('node:path').resolve(__dirname, '../src/latency.ts'), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {} };
vm.runInNewContext(output, context);
const { retainSamples, summarizeLatency, latencyGeometry } = context.exports;
const plain = object => JSON.parse(JSON.stringify(object));
const samples = [{ at: 0, latency: 78 }, { at: 5000, latency: 82 }, { at: 10000, latency: null }, { at: 15000, latency: 90 }, { at: 20000, latency: 80 }];
assert.deepEqual(plain(summarizeLatency([])), { min: null, avg: null, max: null, loss: null });
assert.deepEqual(plain(summarizeLatency(samples)), { min: 78, avg: 83, max: 90, loss: 20 });
assert.equal(retainSamples(samples, 90000).length, 3, 'expired samples must leave the window');
assert.equal(retainSamples(samples, 5000).length, 2, 'future samples must not appear');
const shape = latencyGeometry(samples, 20000);
assert.equal(shape.strokes.length, 2, 'a failed sample must interrupt the line');
assert.equal(latencyGeometry([{ at: 0, latency: 80 }], 0).strokes.length, 0, 'one measurement must not produce a fabricated curve');
assert.equal(latencyGeometry([{ at: 0, latency: 80 }, { at: 20000, latency: 90 }], 20000).strokes.length, 0, 'unsampled time gaps must not be interpolated');
assert.ok(shape.points.every(p => p.x >= 0 && p.x <= 1000 && (p.y === null || p.y >= 0 && p.y <= 200)));
assert.equal(summarizeLatency([{ at: 0, latency: NaN }]).loss, 100);
console.log('PASS: real-sample statistics, probe loss, window expiry, no invented curves, and failed/missing probe gaps.');
